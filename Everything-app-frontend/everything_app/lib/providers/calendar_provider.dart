import 'dart:async';
import 'package:flutter/material.dart';
import '../models/calendar_event.dart';
import '../services/calendar_service.dart';

class CalendarProvider with ChangeNotifier {
  final CalendarService _calendarService;

  List<CalendarEvent> _events = [];
  bool _isLoading = false;
  String? _error;
  DateTime _focusedDay = DateTime.now();
  DateTime? _selectedDay;
  Timer? _pollingTimer;
  bool _hasAutoGenerated = false;

  // calendarService is injectable so tests can supply a fake instead of hitting the network.
  CalendarProvider({CalendarService? calendarService})
      : _calendarService = calendarService ?? CalendarService() {
    _startPolling();
  }

  void _startPolling() {
    _pollingTimer?.cancel();
    // Poll every 30 seconds to catch background SmartScheduler updates
    _pollingTimer = Timer.periodic(const Duration(seconds: 30), (_) {
      _pollEventsSilent();
    });
  }

  Future<void> _pollEventsSilent() async {
    // Only poll if we have a focused day
    try {
      final month = _focusedDay;
      final firstDay = DateTime(month.year, month.month, 1);
      final lastDay = DateTime(month.year, month.month + 1, 0, 23, 59, 59);
      final newEvents = await _calendarService.getEventsInRange(firstDay, lastDay);
      // We could check if events changed before notifying, but for now just update
      _events = newEvents;
      notifyListeners();
    } catch (e) {
      // ignore silently
    }
  }

  @override
  void dispose() {
    _pollingTimer?.cancel();
    super.dispose();
  }

  // Getters
  List<CalendarEvent> get events => _events;
  bool get isLoading => _isLoading;
  String? get error => _error;
  DateTime get focusedDay => _focusedDay;
  DateTime? get selectedDay => _selectedDay;

  List<CalendarEvent> getEventsForDay(DateTime day) {
    return _events.where((event) {
      return event.startTime.year == day.year &&
             event.startTime.month == day.month &&
             event.startTime.day == day.day;
    }).toList();
  }

  
  List<CalendarEvent> get selectedDayEvents {
    if (_selectedDay == null) return [];
    return getEventsForDay(_selectedDay!);
  }

  
  void setFocusedDay(DateTime day) {
    _focusedDay = day;
    notifyListeners();
  }

  
  void setSelectedDay(DateTime? day) {
    _selectedDay = day;
    notifyListeners();
  }

  
  Future<void> loadEventsForMonth(DateTime month) async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      final firstDay = DateTime(month.year, month.month, 1);
      final lastDay = DateTime(month.year, month.month + 1, 0, 23, 59, 59);
      
      _events = await _calendarService.getEventsInRange(firstDay, lastDay);
      _error = null;
    } catch (e) {
      _error = 'Fehler beim Laden der Events: $e';
    }

    _isLoading = false;
    notifyListeners();
  }

  
  Future<void> loadEventsInRange(DateTime start, DateTime end) async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      _events = await _calendarService.getEventsInRange(start, end);
      _error = null;
    } catch (e) {
      _error = 'Fehler beim Laden der Events: $e';
    }

    _isLoading = false;
    notifyListeners();
  }

  
  Future<bool> addEvent(CalendarEvent event) async {
    debugPrint('🕒 [CalendarProvider] addEvent started');
    try {
      debugPrint('🌐 [CalendarProvider] Calling service.createEvent');
      final created = await _calendarService.createEvent(event);
      
      if (created != null) {
        debugPrint('✅ [CalendarProvider] Event created successfully, reloading month');
        await loadEventsForMonth(_focusedDay);
        debugPrint('📊 [CalendarProvider] Month reloaded');
        return true;
      }
      debugPrint('⚠️ [CalendarProvider] service.createEvent returned null');
      return false;
    } catch (e) {
      debugPrint('🔥 [CalendarProvider] Error in addEvent: $e');
      _error = 'Fehler beim Erstellen des Events: $e';
      notifyListeners();
      return false;
    }
  }

  
  // Optimistically applies the change locally (so drag-and-drop feels instant, no
  // full-month reload flicker), then syncs with the backend and reverts on failure.
  Future<bool> updateEvent(CalendarEvent event) async {
    final idx = _events.indexWhere((e) => e.id == event.id);
    final previous = idx != -1 ? _events[idx] : null;

    if (idx != -1) {
      _events[idx] = event;
      notifyListeners();
    }

    try {
      final updated = await _calendarService.updateEvent(event);

      if (updated != null) {
        if (idx != -1) {
          _events[idx] = updated;
          notifyListeners();
        } else {
          await loadEventsForMonth(_focusedDay);
        }
        return true;
      }
      if (idx != -1 && previous != null) {
        _events[idx] = previous;
        notifyListeners();
      }
      return false;
    } catch (e) {
      if (idx != -1 && previous != null) {
        _events[idx] = previous;
      }
      _error = 'Fehler beim Aktualisieren des Events: $e';
      notifyListeners();
      return false;
    }
  }

  
  Future<bool> deleteEvent(int id) async {
    try {
      final success = await _calendarService.deleteEvent(id);
      
      if (success) {
        await loadEventsForMonth(_focusedDay);
        return true;
      }
      return false;
    } catch (e) {
      _error = 'Fehler beim Löschen des Events: $e';
      notifyListeners();
      return false;
    }
  }

  // Backend auto-regenerates on every task/habit/workout/event change (see ScheduleChangedEvent),
  // but items created before that wiring existed (or edited directly in the DB) need one initial
  // backfill pass. Called once per app session — no user-facing button, this is the "automatic"
  // Reclaim-style scheduling entry point.
  Future<void> ensureScheduleGenerated() async {
    if (_hasAutoGenerated) return;
    _hasAutoGenerated = true;
    final now = DateTime.now();
    await generateSchedule(now, now.add(const Duration(days: 14)));
  }


  Future<Map<String, dynamic>> generateSchedule(
    DateTime startDate,
    DateTime endDate,
  ) async {
    _isLoading = true;
    notifyListeners();

    final result = await _calendarService.generateSchedule(startDate, endDate);

    if (result['success']) {
      // Reload events after schedule generation
      await loadEventsInRange(startDate, endDate);
    }

    _isLoading = false;
    notifyListeners();

    return result;
  }

  
  void clearError() {
    _error = null;
    notifyListeners();
  }
}