import 'dart:async';
import 'package:flutter/material.dart';
import '../models/at_risk_item.dart';
import '../models/calendar_event.dart';
import '../services/calendar_service.dart';

class CalendarProvider with ChangeNotifier {
  final CalendarService _calendarService;

  List<CalendarEvent> _events = [];
  bool _isLoading = false;
  String? _error;
  DateTime _focusedDay = DateTime.now();
  DateTime? _selectedDay;
  Timer? _pollingTimer;
  Timer? _reconcileTimer;
  bool _hasAutoGenerated = false;

  /// Wartezeit bis zum Nachladen nach einer Mutation. In Tests auf Duration.zero setzbar,
  /// damit kein laufender Timer die Pending-Timer-Prüfung von flutter_test reißt.
  final Duration reconcileDelay;

  // calendarService is injectable so tests can supply a fake instead of hitting the network.
  CalendarProvider({
    CalendarService? calendarService,
    this.reconcileDelay = const Duration(milliseconds: 2200),
  }) : _calendarService = calendarService ?? CalendarService() {
    _startPolling();
  }

  /// Der Backend-Scheduler plant nach jeder Mutation neu. Ohne diesen Nachlauf sieht der Nutzer
  /// die Umplanung erst beim 30s-Poll — nach einem Drag-and-Drop fühlt sich das kaputt an.
  ///
  /// Das Zeitfenster ist an den echten Ablauf angelegt, nicht geschätzt:
  /// `scheduler.debounce-ms` = 2000 ms Ruhephase, danach ein Lauf von rund einer Sekunde
  /// (Zeitbudget `scheduler.solver-time-limit-seconds` = 2.0 als harte Obergrenze). Der erste
  /// Versuch startet deshalb erst nach der Entprellung — vorher kann sich gar nichts geändert
  /// haben, und der alte erste Poll nach 600 ms war schlicht verschwendet.
  ///
  /// Abgebrochen wird, sobald der Server einen neuen Lauf meldet: die Leiter ist eine
  /// Obergrenze, kein Fahrplan.
  static const List<Duration> _reconcileRetries = [
    Duration(milliseconds: 800),
    Duration(milliseconds: 1200),
    Duration(milliseconds: 1600),
    Duration(milliseconds: 2400),
    Duration(milliseconds: 3000),
  ];

  /// Zeitpunkt des letzten vom Server gemeldeten Laufs — der Abbruchgrund für die Leiter.
  DateTime? _lastRunAt;
  bool _replanning = false;

  /// Läuft gerade eine Neuplanung, auf deren Ergebnis wir warten?
  bool get isReplanning => _replanning;

  /// Aufgaben, die der Scheduler beim letzten Lauf nicht mehr unterbringen konnte.
  List<AtRiskItem> get atRisk => List.unmodifiable(_atRisk);
  List<AtRiskItem> _atRisk = const [];

  /// Davon nur die, bei denen wirklich eine Deadline auf dem Spiel steht.
  ///
  /// Die Quelle fuers Warnband. Alles andere in [atRisk] heisst nur "noch nicht eingeplant" und
  /// gehoert an die Aufgabe selbst, nicht in ein Warnband ueber dem Kalender.
  List<AtRiskItem> get atRiskDeadlines =>
      _atRisk.where((e) => e.isDeadlineRisk).toList(growable: false);

  /// Bereits gerissene Termine — die schaerfere Haelfte von [atRiskDeadlines], eigenes rotes Band.
  List<AtRiskItem> get atRiskOverdue =>
      _atRisk.where((e) => e.isOverdue).toList(growable: false);

  /// Termine, die noch ausstehen, vor denen aber kein Platz mehr ist.
  List<AtRiskItem> get atRiskUpcoming =>
      _atRisk.where((e) => e.isDeadlineRisk && !e.isOverdue).toList(growable: false);

  void scheduleReconcile() {
    _reconcileTimer?.cancel();
    _replanning = true;
    notifyListeners();
    _reconcileTimer = Timer(reconcileDelay, () => _reconcileStep(0));
  }

  Future<void> _reconcileStep(int index) async {
    final fertig = await _pollScheduleStatus();
    if (fertig) {
      // Der Server hat neu geplant — jetzt lohnt sich der teure Abruf, und die Leiter ist zu Ende.
      await _pollEventsSilent();
      _replanning = false;
      notifyListeners();
      return;
    }

    if (index >= _reconcileRetries.length) {
      // Aufgegeben: entweder war gar keine Neuplanung nötig, oder sie dauert ungewöhnlich lang.
      // Der 30s-Poll fängt den Rest auf; hängen bleiben darf die Anzeige dabei nicht.
      await _pollEventsSilent();
      _replanning = false;
      notifyListeners();
      return;
    }
    _reconcileTimer = Timer(_reconcileRetries[index], () => _reconcileStep(index + 1));
  }

  /// True, sobald der Server einen Lauf meldet, der neuer ist als der zuletzt gesehene.
  ///
  /// Die allererste Antwort setzt nur den Ausgangswert und gilt NICHT als Neuplanung: sonst
  /// bräche die Leiter direkt nach dem App-Start ab ("neuer als gar nichts"), noch bevor der
  /// Server angefangen hat.
  Future<bool> _pollScheduleStatus() async {
    final status = await _calendarService.getScheduleStatus();
    if (status == null) return false;

    _atRisk = status.atRisk;
    final laufZeit = status.lastRunAt;
    if (laufZeit == null) return false;

    if (_lastRunAt == null) {
      _lastRunAt = laufZeit;
      return false;
    }
    final neu = laufZeit.isAfter(_lastRunAt!);
    _lastRunAt = laufZeit;
    return neu;
  }

  void _startPolling() {
    _pollingTimer?.cancel();
    // Poll every 30 seconds to catch background SmartScheduler updates
    _pollingTimer = Timer.periodic(const Duration(seconds: 30), (_) {
      _pollEventsSilent();
    });
  }

  Future<void> _pollEventsSilent() async {
    // Only poll if we have a focused day
    try {
      final month = _focusedDay;
      final firstDay = DateTime(month.year, month.month, 1);
      final lastDay = DateTime(month.year, month.month + 1, 0, 23, 59, 59);
      final newEvents = await _calendarService.getEventsInRange(firstDay, lastDay);
      // We could check if events changed before notifying, but for now just update
      _events = newEvents;
      // Die At-Risk-Liste gehoert zum selben Bestand. Sie wurde bisher nur im Nachlauf nach einer
      // eigenen Aenderung aktualisiert — ein Warnband, das ein Hintergrundlauf laengst aufgeloest
      // hatte, blieb deshalb bis zum naechsten Screenwechsel stehen.
      await _pollScheduleStatus();
      notifyListeners();
    } catch (e) {
      // ignore silently
    }
  }

  @override
  void dispose() {
    _pollingTimer?.cancel();
    _reconcileTimer?.cancel();
    super.dispose();
  }

  // Getters

  /// Alle sichtbaren Termine — uebersprungene sind bewusst nicht dabei.
  ///
  /// Ueberspringen gibt die Zeit frei; genau so soll der Tag dann auch aussehen. Bliebe der
  /// Block stehen, wuerde der Scheduler die freigegebene Zeit neu belegen und im Kalender laegen
  /// zwei Bloecke uebereinander — das sieht aus wie ein Fehler, obwohl beides stimmt.
  ///
  /// Der Block selbst bleibt serverseitig erhalten (er ist der Beleg fuer das verbrauchte
  /// Wochenpensum); zurueckholen laesst er sich direkt nach dem Ueberspringen ueber das
  /// Rueckgaengig im Hinweis.
  /// Immer nach Startzeit sortiert.
  ///
  /// Die Serverantwort ist es seit `findByUserIdAndStartTimeBetweenOrderByStartTimeAsc` zwar
  /// auch, aber das allein reicht nicht: die optimistischen Aenderungen hier ersetzen einen
  /// Eintrag AN ORT UND STELLE (`_events[i] = updated`) und `addEvent` haengt hinten an. Ein
  /// verschobener Termin behielte sonst seine alte Position in der Liste — und genau die zeigt
  /// der Homescreen an.
  List<CalendarEvent> get events {
    final sichtbar = _events.where((e) => !e.isSkipped).toList();
    sichtbar.sort((a, b) => a.startTime.compareTo(b.startTime));
    return List.unmodifiable(sichtbar);
  }
  bool get isLoading => _isLoading;
  String? get error => _error;
  DateTime get focusedDay => _focusedDay;
  DateTime? get selectedDay => _selectedDay;

  List<CalendarEvent> getEventsForDay(DateTime day) {
    // Ueber den Getter, damit uebersprungene Bloecke auch hier nicht auftauchen.
    return events.where((event) {
      return event.startTime.year == day.year &&
             event.startTime.month == day.month &&
             event.startTime.day == day.day;
    }).toList();
  }

  /// Was an einem Tag noch bevorsteht — die Sicht des Homescreens.
  ///
  /// Dort steht eine kurze Liste ("die naechsten vier"), und die war am Nachmittag regelmaessig
  /// mit dem Vormittag gefuellt: chronologisch sortiert und oben abgeschnitten zeigte sie genau
  /// das, was schon vorbei war. Gefiltert wird deshalb auf das Ende, nicht auf den Beginn — ein
  /// gerade laufender Block gehoert weiter dazu, bis er wirklich vorbei ist.
  ///
  /// Nur fuer HEUTE. Ein anderer Tag im Datumsstreifen liefert unveraendert den ganzen Tag: dort
  /// ist "was kommt noch" entweder alles (Zukunft) oder nichts (Vergangenheit), und ein leerer
  /// Montag waere keine Antwort, sondern ein Fehler.
  ///
  /// Der Kalender-Screen benutzt das bewusst NICHT — dort bleiben abgehakte Bloecke als Protokoll
  /// sichtbar (durchgestrichen und zurueckgenommen).
  List<CalendarEvent> getUpcomingEventsForDay(DateTime day) {
    final alle = getEventsForDay(day);
    final now = DateTime.now();
    final istHeute = day.year == now.year && day.month == now.month && day.day == now.day;
    if (!istHeute) return alle;

    return alle
        .where((e) => !e.isCompleted && e.endTime.isAfter(now))
        .toList(growable: false);
  }

  List<CalendarEvent> get selectedDayEvents {
    if (_selectedDay == null) return [];
    return getEventsForDay(_selectedDay!);
  }

  
  void setFocusedDay(DateTime day) {
    _focusedDay = day;
    notifyListeners();
  }

  
  void setSelectedDay(DateTime? day) {
    _selectedDay = day;
    notifyListeners();
  }

  
  Future<void> loadEventsForMonth(DateTime month) async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      final firstDay = DateTime(month.year, month.month, 1);
      final lastDay = DateTime(month.year, month.month + 1, 0, 23, 59, 59);
      
      _events = await _calendarService.getEventsInRange(firstDay, lastDay);
      _error = null;
      // Der geladene Monat IST ab jetzt der fokussierte. Ohne diese Zeile laed der 30s-Poll
      // (_pollEventsSilent rechnet aus _focusedDay) gleich wieder einen anderen Monat nach und
      // der gerade geholte Bestand waere nach spaetestens einer halben Minute wieder weg.
      _focusedDay = month;
      // Nebenbei den Ausgangswert für den Nachlauf setzen. Ohne ihn kostet die erste Umplanung
      // nach dem App-Start eine zusätzliche Runde: der Nachlauf müsste erst herausfinden, welcher
      // Lauf der "alte" war, bevor er einen neuen erkennen kann.
      await _pollScheduleStatus();
    } catch (e) {
      _error = 'Fehler beim Laden der Events: $e';
    }

    _isLoading = false;
    notifyListeners();
  }

  
  Future<void> loadEventsInRange(DateTime start, DateTime end) async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      _events = await _calendarService.getEventsInRange(start, end);
      _error = null;
    } catch (e) {
      _error = 'Fehler beim Laden der Events: $e';
    }

    _isLoading = false;
    notifyListeners();
  }

  
  Future<bool> addEvent(CalendarEvent event) async {
    debugPrint('🕒 [CalendarProvider] addEvent started');
    try {
      debugPrint('🌐 [CalendarProvider] Calling service.createEvent');
      final created = await _calendarService.createEvent(event);
      
      if (created != null) {
        debugPrint('✅ [CalendarProvider] Event created successfully, reloading month');
        await loadEventsForMonth(_focusedDay);
        debugPrint('📊 [CalendarProvider] Month reloaded');
        scheduleReconcile();
        return true;
      }
      debugPrint('⚠️ [CalendarProvider] service.createEvent returned null');
      return false;
    } catch (e) {
      debugPrint('🔥 [CalendarProvider] Error in addEvent: $e');
      _error = 'Fehler beim Erstellen des Events: $e';
      notifyListeners();
      return false;
    }
  }

  
  // Optimistically applies the change locally (so drag-and-drop feels instant, no
  // full-month reload flicker), then syncs with the backend and reverts on failure.
  Future<bool> updateEvent(CalendarEvent event) async {
    final idx = _events.indexWhere((e) => e.id == event.id);
    final previous = idx != -1 ? _events[idx] : null;

    if (idx != -1) {
      _events[idx] = event;
      notifyListeners();
    }

    try {
      final updated = await _calendarService.updateEvent(event);

      if (updated != null) {
        if (idx != -1) {
          _events[idx] = updated;
          notifyListeners();
        } else {
          await loadEventsForMonth(_focusedDay);
        }
        // Das Backend plant im Hintergrund um — Ergebnis kurz danach nachladen.
        scheduleReconcile();
        return true;
      }
      if (idx != -1 && previous != null) {
        _events[idx] = previous;
        notifyListeners();
      }
      return false;
    } catch (e) {
      if (idx != -1 && previous != null) {
        _events[idx] = previous;
      }
      _error = 'Fehler beim Aktualisieren des Events: $e';
      notifyListeners();
      return false;
    }
  }

  
  Future<bool> deleteEvent(int id) async {
    try {
      final success = await _calendarService.deleteEvent(id);
      
      if (success) {
        await loadEventsForMonth(_focusedDay);
        scheduleReconcile();
        return true;
      }
      return false;
    } catch (e) {
      _error = 'Fehler beim Löschen des Events: $e';
      notifyListeners();
      return false;
    }
  }

  /// Hakt einen Aufgabenblock ab oder nimmt das zurück.
  ///
  /// Anders als [setPinned] bewusst NICHT optimistisch: der Server schreibt die Minuten gut
  /// (ans Lernziel oder an die Aufgabe), schließt die Aufgabe womöglich ab und plant die
  /// restlichen Blöcke neu. Nichts davon lässt sich hier vorhersagen — also gilt, was
  /// zurückkommt.
  Future<bool> setCompleted(int id, bool completed) async {
    try {
      final updated = await _calendarService.setCompleted(id, completed);
      if (updated == null) return false;

      final idx = _events.indexWhere((e) => e.id == id);
      if (idx != -1) {
        _events[idx] = updated;
        notifyListeners();
      }
      // Die Neuplanung läuft entprellt; das Nachladen holt die verschobenen Blöcke.
      scheduleReconcile();
      return true;
    } catch (e) {
      _error = 'Fehler beim Abhaken des Blocks: $e';
      notifyListeners();
      return false;
    }
  }

  /// Überspringt eine Ausführung oder holt sie zurück.
  ///
  /// Wie [setCompleted] und anders als [setPinned] bewusst NICHT optimistisch: das Überspringen
  /// gibt Zeit frei, stößt eine Neuplanung an und markiert bei einem Training zusätzlich die
  /// Session. Was daraus wird, lässt sich hier nicht vorhersagen — also gilt, was zurückkommt.
  Future<bool> setSkipped(int id, bool skipped) async {
    try {
      final updated = await _calendarService.setSkipped(id, skipped);
      if (updated == null) return false;

      final idx = _events.indexWhere((e) => e.id == id);
      if (idx != -1) {
        _events[idx] = updated;
        notifyListeners();
      }
      // Die freigegebene Zeit füllt der Scheduler entprellt nach.
      scheduleReconcile();
      return true;
    } catch (e) {
      _error = 'Fehler beim Überspringen des Blocks: $e';
      notifyListeners();
      return false;
    }
  }

  /// Pinnt ein Event fest oder gibt es wieder für den Scheduler frei.
  /// Optimistisch wie updateEvent, damit das Schloss-Symbol sofort umspringt.
  Future<bool> setPinned(int id, bool pinned) async {
    final idx = _events.indexWhere((e) => e.id == id);
    final previous = idx != -1 ? _events[idx] : null;

    if (idx != -1 && previous != null) {
      _events[idx] = previous.copyWith(isFixed: pinned);
      notifyListeners();
    }

    try {
      final updated = await _calendarService.setPinned(id, pinned);
      if (updated != null) {
        if (idx != -1) {
          _events[idx] = updated;
          notifyListeners();
        }
        scheduleReconcile();
        return true;
      }
      if (idx != -1 && previous != null) {
        _events[idx] = previous;
        notifyListeners();
      }
      return false;
    } catch (e) {
      if (idx != -1 && previous != null) {
        _events[idx] = previous;
      }
      _error = 'Fehler beim Anpinnen des Events: $e';
      notifyListeners();
      return false;
    }
  }

  // Backend auto-regenerates on every task/habit/workout/event change (see ScheduleChangedEvent),
  // but items created before that wiring existed (or edited directly in the DB) need one initial
  // backfill pass. Called once per app session — no user-facing button, this is the "automatic"
  // Reclaim-style scheduling entry point.
  Future<void> ensureScheduleGenerated() async {
    if (_hasAutoGenerated) return;
    _hasAutoGenerated = true;
    await generateSchedule(DateTime.now());
  }


  // Ohne endDate plant das Backend über seinen vollen Horizont — nur so landen Habits und
  // Workouts in jeder Woche und nicht nur in den nächsten zwei.
  Future<Map<String, dynamic>> generateSchedule(
    DateTime startDate, {
    DateTime? endDate,
  }) async {
    _isLoading = true;
    notifyListeners();

    final result = await _calendarService.generateSchedule(startDate, endDate: endDate);

    if (result['success']) {
      // Bewusst den ganzen Monat neu laden, nicht nur [startDate, endDate]: loadEventsInRange
      // ERSETZT _events durch das 14-Tage-Fenster und löscht damit den Monat, der Millisekunden
      // vorher geladen wurde — frühere Tage im Monat sahen danach leer aus.
      await loadEventsForMonth(_focusedDay);
    }

    _isLoading = false;
    notifyListeners();

    return result;
  }

  
  void clearError() {
    _error = null;
    notifyListeners();
  }
}